  // 지금 시간·요일에 맞는 꼬리표들 ('kind@꼬리표' 대사를 섞는다)
  function momentTags(d = new Date()) {
    const h = d.getHours();
    const day = d.getDay();
    const tags = [h < 5 ? 'dawn' : h < 11 ? 'morning' : h < 17 ? 'afternoon' : h < 21 ? 'evening' : 'night'];
    if (day === 1) tags.push('mon');
    if (day === 5) tags.push('fri');
    if (day === 0 || day === 6) tags.push('weekend');
    return tags;
  }
  const RARE_CHANCE = 0.07;
  // 채울 값이 없는 대사는 고르지 않는다 ({last} 가 없으면 "{last} 또 없어?" 는 빼는 식)
  const canFill = (tpl, vars) => [...String(tpl).matchAll(/\{(\w+)/g)].every((m) => m[1] in vars);

  class Strings {
    constructor(lang, persona) {
      this.lang = DEFAULT_LANG;
      this.persona = DEFAULT_PERSONA;
      this.recent = {}; // 대사 종류마다 최근에 한 말 (같은 말을 연달아 안 하려고)
      this.context = null; // () => { name, m, streak, last… } 대사에 끼울 요즘 사정. main 이 넣어 준다
      this.set(lang, persona);
    }

    set(lang, persona) {
      if (LANGS.includes(lang)) this.lang = lang;
      if (OLD_PERSONA[persona]) persona = OLD_PERSONA[persona];
      if (PERSONAS.includes(persona)) this.persona = persona;
      return this;
    }

    // 버튼·라벨
    t(key, vars) {
      const table = UI[this.lang] || UI[DEFAULT_LANG];
      const v = key in table ? table[key] : UI[DEFAULT_LANG][key];
      return v === undefined ? key : fill(v, vars);
    }

    // 성격에 맞는 대사 후보들. 시간·요일 대사('kind@꼬리표')는 그 언어에 있을 때만 쓴다
    lines(kind) {
      const own = (LINE[this.lang] || LINE[DEFAULT_LANG])[kind];
      const table = own || (kind.includes('@') ? null : LINE[DEFAULT_LANG][kind]);
      if (!table) return [];
      return table[this.persona] || table[DEFAULT_PERSONA] || [];
    }

    // 성격에 맞는 대사 하나. 뻔하지 않게:
    //  - 가끔은 드문 대사('kind@rare')가 튀어나온다
    //  - 지금 시간·요일에만 하는 말이 섞인다
    //  - 최근에 한 말은 한동안 다시 안 한다
    //  - {last}(마지막으로 먹은 것)처럼 요즘 사정을 끼워 넣는다. 채울 값이 없는 대사는 건너뛴다
    line(kind, vars) {
      const all = { ...(this.context ? this.context() : {}), ...(vars || {}) };
      const rare = this.lines(kind + '@rare').filter((t) => canFill(t, all));
      if (rare.length && Math.random() < RARE_CHANCE) return fill(pick(rare), all);
      const every = [...this.lines(kind), ...momentTags().flatMap((tag) => this.lines(kind + '@' + tag))];
      const pool = every.filter((t) => canFill(t, all));
      const list = pool.length ? pool : every;
      if (!list.length) return '';
      const recent = (this.recent[kind] = this.recent[kind] || []);
      const fresh = list.filter((t) => !recent.includes(t));
      const tpl = pick(fresh.length ? fresh : list);
      recent.push(tpl);
      while (recent.length > Math.min(6, Math.floor(list.length / 2))) recent.shift();
      return fill(tpl, all);
    }
  }

  return { Strings, LANGS, PERSONAS, OLD_PERSONA, DEFAULT_LANG, DEFAULT_PERSONA, UI, LINE, josa, fill, pick };
